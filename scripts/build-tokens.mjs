// Generates src/styles/tokens.css and src/tokens.ts from tokens/tokens.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const root = new URL('..', import.meta.url);
const t = JSON.parse(readFileSync(new URL('tokens/tokens.json', root), 'utf8'));
const isLeaf = (o) => o && typeof o === 'object' && 'value' in o;
function flat(obj, prefix = [], out = []) {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('$')) continue;
    if (isLeaf(v)) out.push({ path: [...prefix, k], ...v });
    else flat(v, [...prefix, k], out);
  }
  return out;
}
const { theme, mode, ...rest } = t;
const all = flat(rest);
const name = (p) => '--hd-' + p.join('-');
const lines = (arr, strip = 0) => arr.map((x) => `  ${name(x.path.slice(strip))}: ${x.value};${x.origin === 'ext' ? ' /* extrapolated */' : ''}`).join('\n');
const palette = { light: flat(theme.light, ['c']), dark: flat(theme.dark, ['c']) };
const keys = Object.keys(theme.light);
const SURFACES = ['page', 'card', 'field', 'chrome', 'overlay', 'scrim', 'home', 'banner', 'media'];
/** Remap targets: a component on surface X uses `.hd-on-X`, which re-points every --hd-c-* to X's scheme. */
const ON = ['chrome', 'overlay', 'home', 'banner', 'media', 'card', 'page'];
const modeNames = Object.keys(mode).filter((k) => !k.startsWith('$'));
for (const m of modeNames) for (const s of SURFACES) if (!mode[m][s]) throw new Error(`mode ${m} lacks surface ${s}`);
function modeBlock(m, indent = '  ') {
  const md = mode[m];
  const out = [];
  out.push(`/* page palette (${md.page.scheme}) */`);
  for (const x of palette[md.page.scheme]) out.push(`${name(x.path)}: ${x.value};`);
  out.push(`--hd-c-bg: ${md.page.value};`, `--hd-c-surface: ${md.card.value};`);
  for (const s of SURFACES) {
    const sc = theme[md[s].scheme];
    out.push(`--hd-surface-${s}: ${md[s].value};${md[s].origin === 'ext' ? ' /* extrapolated */' : ''}`);
    out.push(`--hd-surface-${s}-fg: ${sc.fg.value};`, `--hd-surface-${s}-fg-secondary: ${sc['fg-secondary'].value};`, `--hd-surface-${s}-scheme: ${md[s].scheme};`);
    if (ON.includes(s)) for (const k of keys) out.push(`--hd-sx-${s}-${k}: ${k === 'bg' ? md[s].value : k === 'surface' ? (md[s].scheme === 'dark' ? theme.dark['surface-raised'].value : '#FFFFFF') : sc[k].value};`);
  }
  out.push(`color-scheme: ${md.page.scheme};`);
  return out.map((l) => indent + l).join('\n');
}
const sel = {
  hybrid: ':root, [data-hd-mode="hybrid"], .hd-mode-hybrid, .hd-theme-light, [data-hd-theme="light"]',
  dark: '[data-hd-mode="dark"], .hd-mode-dark, .hd-theme-dark, [data-hd-theme="dark"], .hd-inverted',
  light: '[data-hd-mode="light"], .hd-mode-light, [data-hd-mode="auto"], .hd-theme-auto, [data-hd-theme="auto"]',
};
/* Quasar parts that sit on a surface (see src/quasar/harmattan-quasar.css). */
const quasarOn = {
  chrome: ['.hd-quasar .q-footer', '.hd-quasar .q-bar'],
  overlay: ['.hd-quasar .q-menu', '.hd-quasar .q-tooltip', '.hd-quasar .q-bottom-sheet', '.hd-quasar .q-loading__box', '.hd-quasar .q-popup-edit', '.hd-quasar .q-dialog-plugin', '.hd-quasar .q-dialog__inner--minimized:not(.q-dialog__inner--bottom) > .q-card'],
  banner: ['.hd-quasar .q-notification'],
};
const onBlocks = ON.map((s) => `.hd-on-${s}${quasarOn[s] ? ', ' + quasarOn[s].join(', ') : ''} {\n${keys.map((k) => `  --hd-c-${k}: var(--hd-sx-${s}-${k});`).join('\n')}\n  color: var(--hd-c-fg);\n  color-scheme: var(--hd-surface-${s}-scheme);\n}`).join('\n');
const css = `/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */
:root {
${lines(all)}
}
/* Colour modes (docs/15-colour-modes.md). Hybrid = N9 original and the default. */
${modeNames.map((m) => `${sel[m]} {\n${modeBlock(m)}\n}`).join('\n')}
@media (prefers-color-scheme: dark) {
  [data-hd-mode="auto"], .hd-theme-auto, [data-hd-theme="auto"] {
${modeBlock('dark', '    ')}
  }
}
/* Surface scopes: content on chrome/overlay/home/... uses that surface's palette. */
${onBlocks}
`;
mkdirSync(new URL('src/styles/', root), { recursive: true });
writeFileSync(new URL('src/styles/tokens.css', root), css);
const strip = (o) => {
  if (isLeaf(o)) return o.value;
  const r = {};
  for (const [k, v] of Object.entries(o)) if (!k.startsWith('$')) r[k] = strip(v);
  return r;
};
const origins = Object.fromEntries([...all, ...flat(theme, ['theme']), ...flat(mode, ['mode'])].map((x) => [x.path.join('.'), x.origin]));
writeFileSync(new URL('src/tokens.ts', root), `/* GENERATED from tokens/tokens.json. Do not edit. */
export const tokens = ${JSON.stringify(strip(t), null, 2)} as const;
export type Origin = 'n9' | 'ext';
export const tokenOrigins: Record<string, Origin> = ${JSON.stringify(origins, null, 2)};
export const cssVar = (path: string) => \`var(--hd-\${path.replace(/\\./g, '-')})\`;
export default tokens;
`);
console.log(`tokens: ${all.length} global, ${keys.length} palette keys, ${modeNames.length} modes x ${SURFACES.length} surfaces`);
