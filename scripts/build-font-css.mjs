// Generates src/styles/font-alternatives.css from tokens.json font.alternatives (@fontsource latin 300/400/700).
import fs from 'node:fs';
const t = JSON.parse(fs.readFileSync('tokens/tokens.json', 'utf8')).font.alternatives;
const W = { 300: 'Light', 400: 'Regular', 700: 'Bold' };
let css = `/* Metric-adjusted aliases for the free Nokia Pure look-alikes (generated by scripts/build-font-css.mjs).
   Files come from @fontsource packages (OFL-1.1 / Ubuntu Font Licence 1.0); latin subset, 300/400/700.
   size-adjust matches Nokia Pure Text cap height so swapping fonts keeps layouts stable.
   Nokia Pure itself is only referenced via local(): bring your own, it is never bundled. */\n`;
for (const [k, a] of Object.entries(t)) {
  if (k.startsWith('$')) continue;
  const fam = a.family.value.replace(/"/g, '');
  for (const w of [300, 400, 700]) {
    if (k === 'nokia-pure') { css += `@font-face { font-family: "Nokia Pure Text"; font-weight: ${w}; src: local("Nokia Pure Text ${W[w]}"), local("NokiaPureText-${W[w]}"), local("Nokia Pure Text"); }\n`; continue; }
    const f = `${k}-latin-${w}-normal.woff2`;
    if (!fs.existsSync(`node_modules/@fontsource/${k}/files/${f}`)) { console.warn('missing', f); continue; }
    css += `@font-face { font-family: "HD ${fam}"; font-style: normal; font-weight: ${w}; font-display: swap; size-adjust: ${a['size-adjust'].value}; src: url("@fontsource/${k}/files/${f}") format("woff2"); }\n`;
  }
}
fs.writeFileSync('src/styles/font-alternatives.css', css);
console.log('font-alternatives.css written');
